//! Markdown report for one target crate version.

use std::fmt::Write;

use crate::check::{Expected, FunctionResult, Outcome, PointResult};
use crate::compare::Verdict;

/// Rows listed per discrepancy table; the counts always cover every point.
const MAX_ROWS: usize = 20;

fn num(v: f64) -> String {
    if v.is_nan() {
        "NaN".into()
    } else if v.is_infinite() {
        if v.is_sign_positive() {
            "+inf".into()
        } else {
            "-inf".into()
        }
    } else {
        format!("{v:e}")
    }
}

fn list(values: &[f64]) -> String {
    values
        .iter()
        .map(|v| num(*v))
        .collect::<Vec<_>>()
        .join(", ")
}

fn outputs(r: &FunctionResult, values: &crate::data::Values) -> String {
    r.header
        .outputs
        .iter()
        .map(|n| list(&values[n]))
        .collect::<Vec<_>>()
        .join("; ")
}

fn outcome(o: &Outcome) -> String {
    match o {
        Outcome::Value(v) => v.iter().map(|x| list(x)).collect::<Vec<_>>().join("; "),
        Outcome::Error(e) => format!("error: {e}"),
        Outcome::Panic(e) => format!("panic: {e}"),
        Outcome::Timeout(limit) => format!("no result within {} s", limit.as_secs_f64()),
        Outcome::Crash(e) => format!("crash: {e}"),
    }
}

fn inputs(r: &FunctionResult, p: &PointResult) -> String {
    r.header
        .inputs
        .iter()
        .map(|n| format!("{n} = {}", list(&p.point.inputs[n])))
        .collect::<Vec<_>>()
        .join(", ")
}

fn finding(r: &FunctionResult, p: &PointResult) -> String {
    Expected::finding_for(r.check.expected, &p.point.flat_inputs(&r.header)).map_or_else(
        || "**none (unexpected)**".into(),
        |f| format!("[{f}](../findings/{f}.md)"),
    )
}

/// Worst judged error, ignoring tagged and skipped points.
fn worst(r: &FunctionResult) -> Option<&PointResult> {
    r.points
        .iter()
        .filter(|p| !p.error.is_nan())
        .max_by(|a, b| a.error.total_cmp(&b.error))
}

fn table(
    out: &mut String,
    r: &FunctionResult,
    title: &str,
    keep: impl Fn(Verdict) -> bool,
    with_finding: bool,
) {
    let mut rows: Vec<&PointResult> = r.points.iter().filter(|p| keep(p.verdict)).collect();
    if rows.is_empty() {
        return;
    }
    rows.sort_by(|a, b| b.error.total_cmp(&a.error));
    let shown = rows.len().min(MAX_ROWS);
    let _ = writeln!(
        out,
        "\n#### {title} ({} points, worst {shown} shown)\n",
        rows.len()
    );
    let extra = if with_finding { " Finding |" } else { "" };
    let _ = writeln!(
        out,
        "| Inputs | Crate | mpmath | SciPy | Rel. error |{extra}"
    );
    let _ = writeln!(
        out,
        "|---|---|---|---|---|{}",
        if with_finding { "---|" } else { "" }
    );
    for p in rows.into_iter().take(MAX_ROWS) {
        let f = if with_finding {
            format!(" {} |", finding(r, p))
        } else {
            String::new()
        };
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} |{f}",
            inputs(r, p),
            outcome(&p.outcome),
            outputs(r, &p.point.mpmath),
            outputs(r, &p.point.scipy),
            if p.error.is_nan() {
                "tagged".into()
            } else {
                format!("{:.1e}", p.error)
            },
        );
    }
}

/// Renders the report. Deterministic: no timestamps, stable ordering.
#[must_use]
pub fn render(crate_name: &str, version: &str, results: &[FunctionResult]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# {crate_name} {version}: verification report\n");
    let _ = writeln!(
        out,
        "Generated by `cargo test -p check-{crate_name}` from the committed reference data. \
         Do not edit by hand. Verdicts are defined in [docs/conventions.md](../docs/conventions.md).\n"
    );
    let _ = writeln!(out, "## Summary\n");
    let _ = writeln!(
        out,
        "| Function | Points | Pass | Crate wrong | Both wrong | SciPy wrong | Convention | Skipped | Worst rel. error | Tolerance |"
    );
    let _ = writeln!(out, "|---|---|---|---|---|---|---|---|---|---|");
    for r in results {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} | {} | {} | {} | {} | {:.0e} |",
            r.check.function,
            r.points.len(),
            r.count(Verdict::Pass),
            r.count(Verdict::CrateWrong),
            r.count(Verdict::BothWrong),
            r.count(Verdict::ScipyWrong),
            r.count(Verdict::Convention),
            r.count(Verdict::Skipped),
            worst(r).map_or_else(|| "-".into(), |p| format!("{:.1e}", p.error)),
            r.header.tolerance.rel,
        );
    }
    for r in results {
        let h = &r.header;
        let _ = writeln!(out, "\n## `{}`\n", r.check.function);
        let _ = writeln!(
            out,
            "- **Dataset:** `reference/data/{}.jsonl`: {}",
            r.check.dataset, h.description
        );
        let _ = writeln!(
            out,
            "- **References:** mpmath {}, SciPy {}",
            h.mpmath.version, h.scipy.version
        );
        let _ = writeln!(out, "- **Grid:** {}", h.grid);
        let _ = writeln!(
            out,
            "- **Tolerance:** {:e} relative. {}",
            h.tolerance.rel, h.tolerance.reason
        );
        if let Some(p) = worst(r) {
            let _ = writeln!(
                out,
                "- **Worst case:** {} gives {} (mpmath {}), rel. error {:.1e}",
                inputs(r, p),
                outcome(&p.outcome),
                outputs(r, &p.point.mpmath),
                p.error
            );
        }
        table(&mut out, r, "Crate wrong", Verdict::is_crate_failure, true);
        table(
            &mut out,
            r,
            "SciPy wrong, crate right",
            |v| v == Verdict::ScipyWrong,
            false,
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::check::{Check, Expected};
    use crate::data::Dataset;
    use crate::data::tests::sample;

    #[test]
    fn renders_summary_tables_and_findings() {
        const EXP: &[Expected] = &[Expected {
            finding: "001-t-f",
            points: &[&[0.5]],
        }];
        let check = Check {
            function: "t::f",
            dataset: "f",
            expected: EXP,
        };
        let data = Dataset::parse(&sample()).unwrap();
        let r = check.run_on(data, |p| {
            if p.scalar("x") > 0.0 {
                Outcome::scalar(0.2)
            } else {
                Outcome::Error("overflow".into())
            }
        });
        let md = render("t", "1.2.3", &[r]);
        assert!(md.starts_with("# t 1.2.3: verification report\n"));
        assert!(
            md.contains("| `t::f` | 2 | 0 | 1 | 0 | 0 | 1 | 0 | 1.0e0 | 1e-13 |"),
            "{md}"
        );
        assert!(md.contains("#### Crate wrong (1 points, worst 1 shown)"));
        assert!(
            md.contains(
                "| x = 5e-1 | 2e-1 | 1e-1 | 1e-1 | 1.0e0 | [001-t-f](../findings/001-t-f.md) |"
            ),
            "{md}"
        );
        assert!(!md.contains("SciPy wrong, crate right"));
    }

    #[test]
    fn renders_unexpected_failures_scipy_tables_and_specials() {
        let check = Check {
            function: "t::f",
            dataset: "f",
            expected: &[],
        };
        let mut data = Dataset::parse(&sample()).unwrap();
        data.points[0]
            .scipy
            .insert("y".into(), vec![f64::NEG_INFINITY]);
        let r = check.run_on(data, |p| {
            if p.scalar("x") > 0.0 {
                Outcome::scalar(0.1)
            } else {
                Outcome::Panic("boom".into())
            }
        });
        let md = render("t", "1", &[r]);
        assert!(
            md.contains(
                "| x = -3e1 | panic: boom | +inf | -inf | tagged | **none (unexpected)** |"
            ),
            "{md}"
        );
        assert!(md.contains("#### SciPy wrong, crate right (1 points"));
        assert_eq!(num(f64::NAN), "NaN");
        assert_eq!(outcome(&Outcome::Error("e".into())), "error: e");
        assert_eq!(
            outcome(&Outcome::Timeout(std::time::Duration::from_secs(5))),
            "no result within 5 s"
        );
        assert_eq!(
            outcome(&Outcome::Crash("stack overflow".into())),
            "crash: stack overflow"
        );
    }

    #[test]
    fn worst_is_none_when_nothing_is_judged() {
        let check = Check {
            function: "t::f",
            dataset: "f",
            expected: &[],
        };
        let mut data = Dataset::parse(&sample()).unwrap();
        data.points.truncate(1);
        data.points[0].tags = vec![crate::data::Tag::UnstableReference];
        let md = render("t", "1", &[check.run_on(data, |_| Outcome::scalar(0.0))]);
        assert!(md.contains("| 1 | 0 | 0 | 0 | 0 | 0 | 1 | - |"), "{md}");
        assert!(!md.contains("Worst case"));
    }
}
